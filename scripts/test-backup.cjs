const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { backup, restore } = require('./backup-local.cjs');
fs.mkdirSync('.local-data', { recursive: true });
const root = fs.mkdtempSync(path.resolve('.local-data/restore-test-'));
const source = path.join(root, 'source');
fs.mkdirSync(path.join(source, 'visual-editor'), { recursive: true });
fs.writeFileSync(path.join(source, 'db.json'), JSON.stringify({ users: [{ id: 'test' }] }));
fs.writeFileSync(path.join(source, 'visual-editor/home-fr.json'), JSON.stringify({ revision: 2 }));
const archive = path.join(root, 'backup.json');
const target = path.join(root, 'restored');
backup(source, archive); restore(archive, target);
for (const name of ['db.json', 'visual-editor/home-fr.json']) assert.deepEqual(fs.readFileSync(path.join(source, name)), fs.readFileSync(path.join(target, name)));
assert.throws(() => restore(archive, target), /empty directory/);
const corrupted = JSON.parse(fs.readFileSync(archive, 'utf8')); corrupted.entries[0].data = Buffer.from('corrupted').toString('base64');
fs.writeFileSync(path.join(root, 'corrupt.json'), JSON.stringify(corrupted));
assert.throws(() => restore(path.join(root, 'corrupt.json'), path.join(root, 'corrupt-restore')), /checksum/);
corrupted.entries[0].path = '../escape.json'; fs.writeFileSync(path.join(root, 'unsafe.json'), JSON.stringify(corrupted));
assert.throws(() => restore(path.join(root, 'unsafe.json'), path.join(root, 'unsafe-restore')), /Unsafe/);
console.log('PASS: local backup round trip, existing-data protection, corruption and traversal rejection.');
